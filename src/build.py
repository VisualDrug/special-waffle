items=[]
for ch in range(1,35):
    tr=json.load(open(f'{D}ru{ch:02d}.json'))
    for m in meta[str(ch)]:
        t=tr[str(m['n'])]
        t=t+['']*(4-len(t))
        tag=m['tag']
        g=lambda k:(re.search(k+r'=([^\s>]+)',tag) or [None,''])[1]
        money,time,will,lvl,lens=g('钱'),g('时间'),g('毅力'),g('收益'),g('口径')
        W_m={'0':0,'少':1,'多':2};W_t={'少':0,'中':1,'多':2};W_w={'否':0,'些':1,'是':2}
        cs=W_m.get(money,0)+W_t.get(time,0)+W_w.get(will,0)
        ratio='极高' if lvl=='大' and cs==0 else ('高' if (lvl=='大' and cs<=2) or (lvl=='中' and cs==0) else '一般')
        items.append([ch,m['n'],t[0],t[1],t[2],t[3],m['g'],money,time,will,lvl,lens,ratio,1 if m['dis'] else 0,m['url']])
print(len(items))
json.dump(items,open('items.json','w'),ensure_ascii=False)
